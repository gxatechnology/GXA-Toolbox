import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { loadToolRegistry, loadContentPageRegistry, loadToolContentRegistry, PRODUCTION_ORIGIN } from './tool-registry.mjs';

// Build artifacts are the source for admin product facts, never traffic estimates.
export async function generateAdminSnapshot() {
  const tools = await loadToolRegistry();
  const pages = await loadContentPageRegistry();
  const content = await loadToolContentRegistry();
  const ids = new Set(tools.map(tool => tool.id));
  const health = { auditedPublicPages: 0, canonicalIssues: 0, missingTitles: 0, missingDescriptions: 0, missingH1: 0, missingStructuredData: 0, brokenInternalLinks: 0 };
  for (const slug of ['', ...tools.map(tool => tool.id), ...pages.map(page => page.id)]) {
    const html = await readFile(resolve('dist', slug, 'index.html'), 'utf8');
    health.auditedPublicPages++;
    if (!html.includes(`rel="canonical" href="${PRODUCTION_ORIGIN}/${slug ? `${slug}/` : ''}"`)) health.canonicalIssues++;
    if (!/<title>\s*[^<\s][\s\S]*?<\/title>/i.test(html)) health.missingTitles++;
    if (!/<meta\s+name="description"\s+content="[^"]+"/i.test(html)) health.missingDescriptions++;
    if (!/<h1\b[^>]*>[\s\S]*?\S[\s\S]*?<\/h1>/i.test(html)) health.missingH1++;
    const schemas = [...html.matchAll(/<script[^>]*type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/gi)];
    if (!schemas.length || schemas.some(match => { try { JSON.parse(match[1]); return false; } catch { return true; } })) health.missingStructuredData++;
  }
  for (const tool of tools) for (const related of content[tool.id]?.relatedTools || []) {
    if (!ids.has(typeof related === 'string' ? related : related.id)) health.brokenInternalLinks++;
  }
  const snapshot = { tools: tools.map(({ id, name, category }) => ({ id, name, category })), health };
  await writeFile(resolve('netlify/functions/_admin-product-snapshot.mjs'), `// Generated by the SEO build. Do not maintain a second tool registry here.\nexport const ADMIN_PRODUCT_SNAPSHOT = Object.freeze(${JSON.stringify(snapshot, null, 2)});\n`);
  return snapshot;
}
