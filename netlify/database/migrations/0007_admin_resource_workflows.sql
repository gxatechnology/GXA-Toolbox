-- Additive administrator inbox workflows. No user/history/support rows are removed.
-- Read state is per signed administrator subject, not shared with public users.
CREATE TABLE IF NOT EXISTS public.admin_resource_reads (
    actor_subject VARCHAR(128) NOT NULL,
    resource_type VARCHAR(16) NOT NULL,
    resource_id BIGINT NOT NULL,
    read_at TIMESTAMPTZ,
    PRIMARY KEY (actor_subject, resource_type, resource_id),
    CONSTRAINT admin_resource_reads_type CHECK (resource_type IN ('support', 'system')),
    CONSTRAINT admin_resource_reads_positive_id CHECK (resource_id > 0),
    CONSTRAINT admin_resource_reads_actor CHECK (CHAR_LENGTH(BTRIM(actor_subject)) > 0)
);

CREATE TABLE IF NOT EXISTS public.support_message_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    support_message_id BIGINT NOT NULL REFERENCES public.support_messages(id) ON DELETE RESTRICT,
    actor_subject VARCHAR(128) NOT NULL,
    note TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT support_message_notes_length CHECK (CHAR_LENGTH(BTRIM(note)) BETWEEN 1 AND 2000),
    CONSTRAINT support_message_notes_actor CHECK (CHAR_LENGTH(BTRIM(actor_subject)) > 0)
);

CREATE INDEX IF NOT EXISTS support_message_notes_message_idx
    ON public.support_message_notes (support_message_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS user_profiles_created_identity_idx
    ON public.user_profiles (created_at DESC, identity_user_id);
CREATE INDEX IF NOT EXISTS system_events_time_id_idx
    ON public.system_events (occurred_at DESC, id DESC);

