CREATE TABLE IF NOT EXISTS public.blog_slug_redirects (
  old_slug VARCHAR(120) PRIMARY KEY,
  post_id UUID NOT NULL REFERENCES public.blog_posts(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT blog_slug_redirects_slug_valid CHECK (old_slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);
CREATE INDEX IF NOT EXISTS blog_slug_redirects_post_idx ON public.blog_slug_redirects (post_id);

CREATE TABLE IF NOT EXISTS public.blog_audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id UUID REFERENCES public.blog_posts(id) ON DELETE SET NULL,
  actor_subject VARCHAR(128) NOT NULL,
  action VARCHAR(32) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT blog_audit_events_action_valid CHECK (action IN ('create','save','publish','schedule','unpublish','delete','restore_revision','upload_media','change_slug'))
);
CREATE INDEX IF NOT EXISTS blog_audit_events_post_idx ON public.blog_audit_events (post_id, created_at DESC);
