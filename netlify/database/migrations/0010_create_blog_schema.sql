-- Additive blog CMS schema. No existing application rows are changed.
CREATE TABLE IF NOT EXISTS public.blog_posts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  slug VARCHAR(120) NOT NULL UNIQUE,
  title VARCHAR(180) NOT NULL,
  excerpt VARCHAR(500) NOT NULL DEFAULT '',
  content JSONB NOT NULL DEFAULT '[]'::jsonb,
  status VARCHAR(16) NOT NULL DEFAULT 'draft',
  noindex BOOLEAN NOT NULL DEFAULT FALSE,
  author_name VARCHAR(120) NOT NULL DEFAULT 'GXA Technologies',
  featured_media_id UUID,
  meta_title VARCHAR(180),
  meta_description VARCHAR(320),
  og_title VARCHAR(180),
  og_description VARCHAR(320),
  canonical_url VARCHAR(500),
  scheduled_at TIMESTAMPTZ,
  published_at TIMESTAMPTZ,
  significant_updated_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  version INTEGER NOT NULL DEFAULT 1,
  CONSTRAINT blog_posts_slug_valid CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  CONSTRAINT blog_posts_status_valid CHECK (status IN ('draft','scheduled','published','private','deleted')),
  CONSTRAINT blog_posts_content_array CHECK (jsonb_typeof(content) = 'array'),
  CONSTRAINT blog_posts_version_positive CHECK (version > 0),
  CONSTRAINT blog_posts_publish_time_valid CHECK (status <> 'published' OR published_at IS NOT NULL),
  CONSTRAINT blog_posts_schedule_time_valid CHECK (status <> 'scheduled' OR scheduled_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS blog_posts_public_idx ON public.blog_posts (published_at DESC, id DESC)
  WHERE status IN ('published','scheduled') AND noindex = FALSE;
CREATE INDEX IF NOT EXISTS blog_posts_admin_idx ON public.blog_posts (updated_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.blog_post_revisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id UUID NOT NULL REFERENCES public.blog_posts(id) ON DELETE CASCADE,
  version INTEGER NOT NULL,
  snapshot JSONB NOT NULL,
  actor_subject VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT blog_post_revisions_version_positive CHECK (version > 0),
  CONSTRAINT blog_post_revisions_unique UNIQUE (post_id, version)
);
CREATE INDEX IF NOT EXISTS blog_post_revisions_post_idx ON public.blog_post_revisions (post_id, version DESC);

CREATE TABLE IF NOT EXISTS public.blog_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  CONSTRAINT blog_categories_slug_valid CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);
CREATE TABLE IF NOT EXISTS public.blog_tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  CONSTRAINT blog_tags_slug_valid CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);
CREATE TABLE IF NOT EXISTS public.blog_post_categories (
  post_id UUID NOT NULL REFERENCES public.blog_posts(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES public.blog_categories(id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, category_id)
);
CREATE TABLE IF NOT EXISTS public.blog_post_tags (
  post_id UUID NOT NULL REFERENCES public.blog_posts(id) ON DELETE CASCADE,
  tag_id BIGINT NOT NULL REFERENCES public.blog_tags(id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, tag_id)
);
CREATE TABLE IF NOT EXISTS public.blog_media (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  blob_key VARCHAR(200) NOT NULL UNIQUE,
  content_type VARCHAR(32) NOT NULL,
  byte_size INTEGER NOT NULL,
  width INTEGER NOT NULL,
  height INTEGER NOT NULL,
  alt_text VARCHAR(240) NOT NULL,
  caption VARCHAR(300) NOT NULL DEFAULT '',
  created_by VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT blog_media_type_valid CHECK (content_type IN ('image/jpeg','image/png','image/webp')),
  CONSTRAINT blog_media_size_valid CHECK (byte_size BETWEEN 1 AND 5000000),
  CONSTRAINT blog_media_dimensions_valid CHECK (width BETWEEN 1 AND 6000 AND height BETWEEN 1 AND 6000)
);
CREATE TABLE IF NOT EXISTS public.blog_post_media (
  post_id UUID NOT NULL REFERENCES public.blog_posts(id) ON DELETE CASCADE,
  media_id UUID NOT NULL REFERENCES public.blog_media(id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, media_id)
);
CREATE INDEX IF NOT EXISTS blog_post_media_media_idx ON public.blog_post_media (media_id);
