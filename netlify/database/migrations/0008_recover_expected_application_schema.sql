DO $$
DECLARE target RECORD;
BEGIN
  FOR target IN SELECT * FROM (VALUES
    ('users','users_set_updated_at'),
    ('user_profiles','user_profiles_set_updated_at'),
    ('file_jobs','file_jobs_set_updated_at'),
    ('support_messages','support_messages_set_updated_at'),
    ('admin_profiles','admin_profiles_set_updated_at')
  ) AS triggers(table_name, trigger_name)
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_trigger
       WHERE tgname = target.trigger_name
         AND tgrelid = format('public.%I', target.table_name)::regclass
         AND NOT tgisinternal
    ) THEN
      EXECUTE format(
        'CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.gxa_set_updated_at()',
        target.trigger_name, target.table_name
      );
    END IF;
  END LOOP;
END
$$;
