CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(24) NOT NULL DEFAULT 'user',
    is_premium BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(24) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ,
    CONSTRAINT users_email_unique UNIQUE (email),
    CONSTRAINT users_email_normalized CHECK (email = LOWER(BTRIM(email))),
    CONSTRAINT users_full_name_not_blank CHECK (CHAR_LENGTH(BTRIM(full_name)) >= 2),
    CONSTRAINT users_role_valid CHECK (role IN ('developer', 'admin', 'user')),
    CONSTRAINT users_status_valid CHECK (status IN ('active', 'inactive'))
);

ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ;

CREATE OR REPLACE FUNCTION public.gxa_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS public.user_profiles (
    identity_user_id TEXT PRIMARY KEY,
    legacy_user_id BIGINT UNIQUE,
    email VARCHAR(254) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    provider VARCHAR(32) NOT NULL DEFAULT 'email',
    status VARCHAR(24) NOT NULL DEFAULT 'active',
    is_premium BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ,
    CONSTRAINT user_profiles_email_normalized CHECK (email = LOWER(BTRIM(email))),
    CONSTRAINT user_profiles_full_name_not_blank CHECK (CHAR_LENGTH(BTRIM(full_name)) >= 1),
    CONSTRAINT user_profiles_provider_not_blank CHECK (CHAR_LENGTH(BTRIM(provider)) >= 1),
    CONSTRAINT user_profiles_status_valid CHECK (status IN ('active', 'inactive')),
    CONSTRAINT user_profiles_legacy_user_fk FOREIGN KEY (legacy_user_id) REFERENCES public.users(id) ON DELETE SET NULL
);

ALTER TABLE public.user_profiles
    ADD COLUMN IF NOT EXISTS provider VARCHAR(32) NOT NULL DEFAULT 'email';

CREATE TABLE IF NOT EXISTS public.file_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    identity_user_id TEXT,
    tool_name VARCHAR(100) NOT NULL,
    original_file VARCHAR(255) NOT NULL,
    output_file VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'done',
    size_mb NUMERIC(12,4) NOT NULL DEFAULT 0,
    processing_time_ms INTEGER NOT NULL DEFAULT 0,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT file_jobs_tool_name_not_blank CHECK (CHAR_LENGTH(BTRIM(tool_name)) > 0),
    CONSTRAINT file_jobs_original_file_not_blank CHECK (CHAR_LENGTH(BTRIM(original_file)) > 0),
    CONSTRAINT file_jobs_output_file_not_blank CHECK (CHAR_LENGTH(BTRIM(output_file)) > 0),
    CONSTRAINT file_jobs_size_nonnegative CHECK (size_mb >= 0),
    CONSTRAINT file_jobs_processing_time_nonnegative CHECK (processing_time_ms >= 0),
    CONSTRAINT file_jobs_user_fk FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL,
    CONSTRAINT file_jobs_identity_user_fk FOREIGN KEY (identity_user_id) REFERENCES public.user_profiles(identity_user_id) ON DELETE SET NULL
);

ALTER TABLE public.file_jobs
    ADD COLUMN IF NOT EXISTS identity_user_id TEXT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname = 'file_jobs_identity_user_fk'
           AND conrelid = 'public.file_jobs'::regclass
    ) THEN
        ALTER TABLE public.file_jobs
            ADD CONSTRAINT file_jobs_identity_user_fk
            FOREIGN KEY (identity_user_id) REFERENCES public.user_profiles(identity_user_id) ON DELETE SET NULL;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.tool_analytics_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(32) NOT NULL CHECK (event_type IN ('tool_open','tool_start','tool_complete','tool_fail','tool_download')),
    tool_id VARCHAR(100) NOT NULL CHECK (tool_id ~ '^[a-z0-9-]{1,100}$'),
    tool_name VARCHAR(120) NOT NULL,
    tool_category VARCHAR(40) NOT NULL CHECK (CHAR_LENGTH(BTRIM(tool_category)) > 0),
    status VARCHAR(40),
    duration_bucket VARCHAR(32),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.auth_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(32) NOT NULL CHECK (event_type IN ('registration_success','registration_failure','login_success','login_failure','session_failure')),
    category VARCHAR(64) NOT NULL CHECK (CHAR_LENGTH(BTRIM(category)) > 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.system_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(64) NOT NULL CHECK (CHAR_LENGTH(BTRIM(source)) > 0),
    category VARCHAR(80) NOT NULL CHECK (CHAR_LENGTH(BTRIM(category)) > 0),
    severity VARCHAR(16) NOT NULL DEFAULT 'error' CHECK (severity IN ('info','warning','error')),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.support_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_user_id TEXT REFERENCES public.user_profiles(identity_user_id) ON DELETE SET NULL,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'new',
    dedupe_key CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT support_messages_name_not_blank CHECK (CHAR_LENGTH(BTRIM(full_name)) BETWEEN 2 AND 120),
    CONSTRAINT support_messages_email_normalized CHECK (email = LOWER(BTRIM(email))),
    CONSTRAINT support_messages_message_length CHECK (CHAR_LENGTH(BTRIM(message)) BETWEEN 10 AND 4000),
    CONSTRAINT support_messages_status_valid CHECK (status IN ('new','in_progress','resolved'))
);

CREATE TABLE IF NOT EXISTS public.admin_profiles (
    subject VARCHAR(128) PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL DEFAULT '',
    display_name VARCHAR(80) NOT NULL DEFAULT '',
    phone VARCHAR(40) NOT NULL DEFAULT '',
    theme VARCHAR(12) NOT NULL DEFAULT 'system' CHECK (theme IN ('system','light','dark')),
    sidebar_collapsed BOOLEAN NOT NULL DEFAULT FALSE,
    avatar_revision UUID,
    avatar_image BYTEA,
    avatar_thumbnail BYTEA,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ,
    CONSTRAINT admin_profile_subject_valid CHECK (subject ~ '^[a-zA-Z0-9_-]{1,128}$'),
    CONSTRAINT admin_avatar_bounded CHECK (
      (avatar_revision IS NULL AND avatar_image IS NULL AND avatar_thumbnail IS NULL)
      OR (avatar_revision IS NOT NULL AND avatar_image IS NOT NULL AND avatar_thumbnail IS NOT NULL
        AND OCTET_LENGTH(avatar_image) BETWEEN 1 AND 131072
        AND OCTET_LENGTH(avatar_thumbnail) BETWEEN 1 AND 32768)
    )
);

CREATE TABLE IF NOT EXISTS public.admin_audit_events (
