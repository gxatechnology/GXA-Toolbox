-- The existing environment-managed administrator remains the authentication source.
-- This additive profile stores preferences and bounded, private avatar renditions only.
CREATE TABLE IF NOT EXISTS public.admin_profiles (
    subject VARCHAR(128) PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL DEFAULT '',
    display_name VARCHAR(80) NOT NULL DEFAULT '',
    phone VARCHAR(40) NOT NULL DEFAULT '',
    theme VARCHAR(12) NOT NULL DEFAULT 'system',
    sidebar_collapsed BOOLEAN NOT NULL DEFAULT FALSE,
    avatar_revision UUID,
    avatar_image BYTEA,
    avatar_thumbnail BYTEA,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ,
    CONSTRAINT admin_profile_subject_valid CHECK (subject ~ '^[a-zA-Z0-9_-]{1,128}$'),
    CONSTRAINT admin_profile_theme_valid CHECK (theme IN ('system', 'light', 'dark')),
    CONSTRAINT admin_avatar_bounded CHECK (
        (avatar_revision IS NULL AND avatar_image IS NULL AND avatar_thumbnail IS NULL)
        OR (avatar_revision IS NOT NULL AND avatar_image IS NOT NULL AND avatar_thumbnail IS NOT NULL
            AND OCTET_LENGTH(avatar_image) BETWEEN 1 AND 131072
            AND OCTET_LENGTH(avatar_thumbnail) BETWEEN 1 AND 32768)
    )
);

CREATE TABLE IF NOT EXISTS public.admin_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_subject VARCHAR(128) NOT NULL,
    action VARCHAR(64) NOT NULL,
    resource_type VARCHAR(64) NOT NULL,
    resource_id VARCHAR(160) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT admin_audit_actor_valid CHECK (actor_subject ~ '^[a-zA-Z0-9_-]{1,128}$'),
    CONSTRAINT admin_audit_action_valid CHECK (action ~ '^[a-z0-9_]{1,64}$'),
    CONSTRAINT admin_audit_resource_type_valid CHECK (resource_type ~ '^[a-z0-9_]{1,64}$'),
    CONSTRAINT admin_audit_resource_id_valid CHECK (CHAR_LENGTH(resource_id) BETWEEN 1 AND 160)
);

CREATE INDEX IF NOT EXISTS admin_audit_occurred_idx ON public.admin_audit_events (occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS admin_audit_actor_occurred_idx ON public.admin_audit_events (actor_subject, occurred_at DESC);

-- One row per actor/action bucket, reused each window: no unbounded per-request rows.
CREATE TABLE IF NOT EXISTS public.admin_rate_limits (
    actor_subject VARCHAR(128) NOT NULL,
    bucket VARCHAR(40) NOT NULL,
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempts INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (actor_subject, bucket),
    CONSTRAINT admin_rate_attempts_positive CHECK (attempts > 0),
    CONSTRAINT admin_rate_bucket_valid CHECK (bucket ~ '^[a-z0-9_]{1,40}$')
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'admin_profiles_set_updated_at'
          AND tgrelid = 'public.admin_profiles'::regclass AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER admin_profiles_set_updated_at BEFORE UPDATE ON public.admin_profiles
        FOR EACH ROW EXECUTE FUNCTION public.gxa_set_updated_at();
    END IF;
END
$$;
