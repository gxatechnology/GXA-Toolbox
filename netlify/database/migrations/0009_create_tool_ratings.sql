-- Additive, privacy-minimized ratings schema for GXA Toolbox.
-- No existing rows are changed or removed. Production submission remains gated
-- by TOOL_RATINGS_ENABLED and RATING_ABUSE_SECRET in the server function.

CREATE TABLE IF NOT EXISTS public.tool_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_id VARCHAR(100) NOT NULL,
    rating SMALLINT NOT NULL,
    review TEXT,
    moderation_status VARCHAR(16) NOT NULL DEFAULT 'pending',
    abuse_key CHAR(64) NOT NULL,
    submission_day DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    moderated_at TIMESTAMPTZ,
    moderated_by VARCHAR(128),
    CONSTRAINT tool_ratings_tool_id_valid CHECK (tool_id ~ '^[a-z0-9-]{1,100}$'),
    CONSTRAINT tool_ratings_value_valid CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT tool_ratings_review_length CHECK (review IS NULL OR CHAR_LENGTH(BTRIM(review)) BETWEEN 1 AND 1000),
    CONSTRAINT tool_ratings_moderation_valid CHECK (moderation_status IN ('pending','accepted','rejected','spam')),
    CONSTRAINT tool_ratings_abuse_key_valid CHECK (abuse_key ~ '^[a-f0-9]{64}$'),
    CONSTRAINT tool_ratings_moderator_valid CHECK (moderated_by IS NULL OR moderated_by ~ '^[a-zA-Z0-9_-]{1,128}$'),
    CONSTRAINT tool_ratings_daily_submission_unique UNIQUE (tool_id, abuse_key, submission_day)
);

CREATE INDEX IF NOT EXISTS tool_ratings_tool_created_idx
    ON public.tool_ratings (tool_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS tool_ratings_moderation_created_idx
    ON public.tool_ratings (moderation_status, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS tool_ratings_abuse_created_idx
    ON public.tool_ratings (abuse_key, created_at DESC);

-- Ratings remain part of the aggregate while a written review is pending or
-- hidden. Only submissions explicitly classified as spam are excluded.
CREATE OR REPLACE VIEW public.tool_rating_aggregates AS
SELECT
    tool_id,
    COUNT(*) FILTER (WHERE moderation_status <> 'spam')::INTEGER AS rating_count,
    ROUND(AVG(rating) FILTER (WHERE moderation_status <> 'spam')::NUMERIC, 2) AS average_rating,
    COUNT(*) FILTER (WHERE moderation_status <> 'spam' AND rating = 1)::INTEGER AS one_star,
    COUNT(*) FILTER (WHERE moderation_status <> 'spam' AND rating = 2)::INTEGER AS two_star,
    COUNT(*) FILTER (WHERE moderation_status <> 'spam' AND rating = 3)::INTEGER AS three_star,
    COUNT(*) FILTER (WHERE moderation_status <> 'spam' AND rating = 4)::INTEGER AS four_star,
    COUNT(*) FILTER (WHERE moderation_status <> 'spam' AND rating = 5)::INTEGER AS five_star,
    MAX(GREATEST(created_at, COALESCE(moderated_at, created_at))) AS last_updated_at
FROM public.tool_ratings
GROUP BY tool_id;

COMMENT ON TABLE public.tool_ratings IS
  'Privacy-minimized tool ratings. No raw IP address or user-agent is stored.';
COMMENT ON VIEW public.tool_rating_aggregates IS
  'Verified aggregates calculated from persisted ratings; spam is excluded.';
