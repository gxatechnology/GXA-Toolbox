import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import { loadToolQuality } from '../scripts/tool-registry.mjs';
const read = path => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
const dom = new JSDOM('<main id="main-content"><section class="tool-container"><div class="tool-workspace" data-tool-id="resize-image"><input id="file-picker" type="file"><div id="tool-queue-mount"><button id="btn-process-action">Resize</button></div><aside class="tool-sidebar-settings"><div class="tool-options-panel"><input id="width"></div></aside><div id="premium-editor-toolbar" hidden></div></div><div class="premium-session-panel"></div></section></main>', { runScripts: 'outside-only' });
// This contract drives sync directly; provide the browser frame scheduler too.
dom.window.requestAnimationFrame = callback => dom.window.setTimeout(callback, 0);
dom.window.appState = { activeFiles: [] };
dom.window.eval(await read('public_html/assets/tool-ux.js'));
const sync = dom.window.GxaToolUx.sync;
const find = selector => dom.window.document.querySelector(selector);
sync();
assert.equal(find('.tool-container').dataset.disclosure, 'upload');
assert.equal(find('.tool-sidebar-settings').hidden, true);
dom.window.appState.activeFiles = [{ name: 'test.png' }]; sync();
assert.equal(find('.tool-sidebar-settings').hidden, false);
assert.equal(find('#btn-process-action').parentElement, find('.tool-options-panel'));
assert.equal(find('#premium-editor-toolbar').hidden, true, 'Empty toolbar remains absent');
find('#tool-queue-mount').classList.add('hidden'); sync();
assert.equal(find('#btn-process-action').hidden, true, 'Do not offer a second action while processing/result is displayed');
dom.window.appState.activeFiles = []; sync();
assert.equal(find('.tool-sidebar-settings').hidden, true, 'Reset returns to upload-first state');
dom.window.close();
const editorDom = new JSDOM('<main id="main-content"><section class="tool-container edit-pdf-page"><div class="pdf-edit"><div class="pdf-edit-document" hidden></div></div><article class="tool-content-guide"><section class="tool-preworkspace-intro">Technical explanation</section></article></section></main>', { runScripts: 'outside-only' });
editorDom.window.requestAnimationFrame = callback => editorDom.window.setTimeout(callback, 0);
editorDom.window.eval(await read('public_html/assets/tool-ux.js'));
editorDom.window.GxaToolUx.sync();
assert.equal(editorDom.window.document.querySelector('.tool-container').dataset.disclosure, 'upload');
editorDom.window.document.querySelector('.pdf-edit-document').hidden = false;
editorDom.window.GxaToolUx.sync();
assert.equal(editorDom.window.document.querySelector('.tool-container').dataset.disclosure, 'ready');
assert.equal(editorDom.window.document.querySelector('.tool-preworkspace-intro').hidden, false);
editorDom.window.close();
const quality = await loadToolQuality();
assert.equal(Object.values(quality).filter(q => q.indexable).length, 81);
assert.equal(Object.values(quality).filter(q => !q.adsEligible).length, 14);
const app = await read('public_html/assets/app.js');
assert.match(app, /data-ad-zone=/);
assert.match(app, /forPage\(appState.currentPage, toolsList\).adsEligible/);
assert.doesNotMatch(app, /Precision controls|Clear processing details|Access powerful browser-based/);
assert.match(await read('public_html/assets/tool-content.js'), /signed-in operations can save filenames/);
assert.match(await read('index.html'), /tool-ux.js/);
assert.match(await read('public_html/index.php'), /tool-ux.js/);
console.log('Phase 3 contract passed: upload/ready/reset, action ordering, empty toolbar, unchanged 81/14 policy, privacy and optional ad zones.');
